/** An over-limit vendor (9 venues on a plan that allows 4) picks which stay live.  node overlimit.cjs <tag> [w] [h]  (backend needs PLAN_LIMITS_ENFORCE=all) */
const L = require("./lib.cjs")
const K = L.K
;(async () => {
  const [tag, w = "1536", h = "864"] = process.argv.slice(2)
  const b = await L.launch()
  const ctx = await L.uiLogin(b, K.CREDS.vendor.email, { width: +w, height: +h }, K.CREDS.vendor.password)
  const page = await ctx.newPage()
  const errors = []
  page.on("pageerror", (e) => errors.push(String(e).slice(0, 160)))
  const calls = []
  page.on("response", async (r) => { if (/live-venues/.test(r.url())) calls.push(`${r.status()} ${r.request().method()} ${(await r.text().catch(() => "")).slice(0, 240)}`) })
  await page.goto(L.BASE + "/dashboard/billing#over", { waitUntil: "domcontentloaded", timeout: 180000 })
  await page.waitForSelector("[data-testid=over-limit-card]", { timeout: 120000 }).catch(() => console.log("no over-limit card"))
  await page.waitForTimeout(2500)
  await L.shot(page, `${tag}-over-card`)
  console.log("GET live-venues:", calls[0])
  await page.locator("[data-live-open]").click()
  await page.waitForSelector("[data-live-form]", { timeout: 20000 })
  await page.waitForTimeout(800)
  await L.shot(page, `${tag}-over-drawer`)
  const rows = await page.locator("[data-live-form] input[type=checkbox]").count()
  const checked = await page.locator("[data-live-form] input[type=checkbox]:checked").count()
  console.log("venues in drawer:", rows, "pre-ticked:", checked, "| count text:", await page.locator("[data-live-count]").innerText())
  // untick everything, then tick exactly five (one too many) to see the refusal, then four
  for (let i = 0; i < rows; i++) { const c = page.locator("[data-live-form] input[type=checkbox]").nth(i); if (await c.isChecked()) await c.uncheck() }
  for (let i = 0; i < 5; i++) await page.locator("[data-live-form] input[type=checkbox]").nth(i).check()
  await page.locator("[data-live-save]").click()
  await page.waitForTimeout(1200)
  console.log("5 ticked ->", await page.locator("#live-err").innerText())
  await L.shot(page, `${tag}-over-drawer-five`)
  await page.locator("[data-live-form] input[type=checkbox]").nth(4).uncheck()
  await page.locator("[data-live-save]").click()
  await page.waitForTimeout(4500)
  console.log("saved; calls:", calls.slice(1).join(" | "))
  await page.reload({ waitUntil: "domcontentloaded" })
  await page.waitForSelector("[data-testid=over-limit-card]", { timeout: 60000 }).catch(() => {})
  await page.waitForTimeout(3000)
  await L.shot(page, `${tag}-over-card-after`)
  const lv = await K.api("vendor", "GET", "/subscriptions/live-venues")
  console.log("API live:", JSON.stringify(lv.body && lv.body.data && lv.body.data.venues.map((v) => `${v.id}:${v.live ? "live" : "paused"}`)), "limit", lv.body && lv.body.data && lv.body.data.limit)
  console.log("errors:", errors.length ? errors.join(" | ") : "NONE")
  await b.close()
  process.exit(0)
})().catch((e) => { console.error("FAILED", e); process.exit(1) })
