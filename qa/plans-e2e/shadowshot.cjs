const L = require("./lib.cjs")
;(async () => {
  const b = await L.launch()
  const ctx = await L.uiLogin(b, L.K.CREDS.admin.email, { width: 1536, height: 864 }, L.K.CREDS.admin.password)
  const page = await ctx.newPage()
  await page.goto(`${L.BASE}/dashboard/admin/billing-tools`, { waitUntil: "domcontentloaded", timeout: 180000 })
  await page.getByRole("tab", { name: "Shadow report" }).click(); await page.waitForTimeout(4500)
  await L.shot(page, "t02-tab-shadow")
  await page.getByRole("tab", { name: "Audit log" }).click(); await page.waitForTimeout(3500)
  await L.shot(page, "t02-tab-audit")
  await page.getByRole("tab", { name: "Expiring" }).click(); await page.waitForTimeout(3500)
  await L.shot(page, "t02-tab-expiring")
  await b.close(); process.exit(0)
})().catch((e) => { console.error("FAILED", e.message.slice(0, 300)); process.exit(1) })
