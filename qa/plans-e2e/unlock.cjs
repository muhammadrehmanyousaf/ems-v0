/** After an approval / renewal: the vendor is open at once and every record is where it was.  node unlock.cjs <email> <userId> <tag> '<json counts before>' */
const L = require("./lib.cjs")
;(async () => {
  const [email, userId, tag, before] = process.argv.slice(2)
  const t0 = Date.now()
  const st = await L.status(email)
  console.log("status now:", JSON.stringify({ state: st.state, plan: st.planName, periodEndsAt: st.periodEndsAt, accessEndsAt: st.accessEndsAt, daysLeft: st.daysLeft, lockedAt: st.lockedAt }), "in", Date.now() - t0, "ms")
  const after = await L.counts(Number(userId))
  console.log("counts after :", JSON.stringify(after))
  if (before) console.log("counts before:", before, "| identical:", JSON.stringify(after) === JSON.stringify(JSON.parse(before)))
  const b = await L.launch()
  const ctx = await L.uiLogin(b, email)
  const page = await ctx.newPage()
  const api = []
  page.on("response", (r) => { const u = r.url(); if (u.includes(":5134/api/v1/")) api.push(r.status()) })
  await page.goto(L.BASE + "/dashboard/bookings", { waitUntil: "domcontentloaded", timeout: 180000 })
  await page.waitForSelector("[data-testid=plan-banners], [data-testid=plan-chip], [data-testid=access-wall]", { timeout: 90000 }).catch(() => {})
  await page.waitForTimeout(4000)
  const info = await page.evaluate(() => ({ wall: !!document.querySelector("[data-testid=access-wall]"), banners: Array.from(document.querySelectorAll("[data-kind]")).map((e) => e.getAttribute("data-kind")), chip: document.querySelector("[data-testid=plan-chip]")?.textContent || null, rows: document.body.innerText.match(/(\d+) bookings?/g) }))
  console.log("UI:", JSON.stringify(info), "| 402s on this load:", api.filter((s) => s === 402).length, "| 200s:", api.filter((s) => s === 200).length)
  await L.shot(page, `${tag}-unlocked-bookings`)
  await b.close()
  process.exit(0)
})().catch((e) => { console.error("FAILED", e); process.exit(1) })
