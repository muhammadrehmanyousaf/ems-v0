/**
 * Writes one Cypress spec file per module, from cypress/fixtures/modules.json.
 *
 *   node scripts/cypress-generate-module-specs.mjs
 *
 * One file per module because that is how a failure gets read: "Suppliers is
 * red" is actionable, "the sweep is red" is not. Each file wires the shared
 * contract in `cypress/support/module-suite.ts` and then leaves a marked block
 * for that module's own cases.
 *
 * Existing files are NEVER overwritten. Once a module's file has hand-written
 * depth in it, regenerating must not silently delete that work — the generator
 * only fills in the ones that do not exist yet, and says which it skipped.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const specDir = resolve(root, "cypress/e2e/10-modules");

const { modules } = JSON.parse(
  readFileSync(resolve(root, "cypress/fixtures/modules.json"), "utf8"),
);

const slug = (route) =>
  route.replace(/^\/dashboard\/?/, "").replace(/\//g, "-").replace(/[^a-z0-9-]/gi, "") || "home";

mkdirSync(specDir, { recursive: true });

let written = 0;
const skipped = [];

for (const mod of modules) {
  const file = resolve(specDir, `${slug(mod.route)}.cy.ts`);
  if (existsSync(file)) {
    skipped.push(slug(mod.route));
    continue;
  }

  const expects = JSON.stringify(mod.expects, null, 4)
    .split("\n")
    .map((l, i) => (i === 0 ? l : `  ${l}`))
    .join("\n");

  writeFileSync(
    file,
    `/**
 * ${mod.name} — ${mod.route}
 *
 * Generated by scripts/cypress-generate-module-specs.mjs, then extended by
 * hand. The generator will not overwrite this file again.
 *
 * \`moduleSuite\` is the shared contract every module must satisfy —
 * reachability, no console errors, no failing API calls, no horizontal
 * overflow at 1366 or 360, accessible names, heading order, focus ring. Add
 * cases specific to ${mod.name} in the block underneath it: the contract is
 * the floor, not the test plan.
 */
import { moduleSuite } from "../../support/module-suite";

moduleSuite({
  route: "${mod.route}",
  name: "${mod.name}",${mod.adminOnly ? "\n  adminOnly: true," : ""}
  expects: ${expects},
});

// ─── ${mod.name}-specific cases ─────────────────────────────────────────────
// Nothing here yet. A module with only the shared contract is COVERED, not
// TESTED — the contract proves the screen is not broken, not that the feature
// works. See leads.cy.ts for the depth each module is heading towards.
`,
  );
  written += 1;
}

console.log(
  `cypress/e2e/10-modules — ${written} spec files written` +
    (skipped.length ? `, ${skipped.length} left alone (already exist): ${skipped.join(", ")}` : ""),
);
